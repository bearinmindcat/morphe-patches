package org.ungoogled.patches.honorcalculator.misc

import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import app.morphe.patcher.patch.resourcePatch
import org.ungoogled.patches.honor.followMagicDayNight
import org.ungoogled.patches.honor.replaceMagicFrameworkReferences
import org.ungoogled.patches.honorcalculator.HonorCalculatorConstants.COMPATIBILITY_HONOR_CALCULATOR

internal const val HONOR_CALCULATOR_EXTENSION = "extensions/honorcalculator.mpe"

private val log = java.util.logging.Logger.getLogger("HonorCalculator")

/**
 * Calculator's layouts and styles take their side margins and two text sizes from MagicOS's theme (see
 * replaceMagicFrameworkReferences), and its screens follow dark mode through MagicOS's theme (see followMagicDayNight).
 */
private val magicResourcesPatch = resourcePatch(
    description = "Gives Honor Calculator the sizes and day/night theme MagicOS would.",
) {
    execute {
        val replaced = replaceMagicFrameworkReferences()
        log.info("MagicOS framework references: $replaced")
        // Measured against 12.0.1.217: maxPaddingStart/End in 26 layouts and 3 styles, textSizeSubTitle3, textSizeBody2.
        if (replaced.size < 4) throw PatchException("only ${replaced.size} MagicOS framework references found")

        val (activities, styles) = followMagicDayNight()
        log.info("Day/night themes: $activities activities, $styles styles")
        // Measured: History and the lock-screen calculator name Android's Holo theme, the calculator its own Theme.
        if (activities < 2 || styles < 1) throw PatchException("themes changed: $activities activities, $styles styles")
    }
}

/**
 * Off MagicOS Calculator dies at once on com.hihonor.android.os.SystemPropertiesEx (a MagicOS framework class), and its
 * layouts then on MagicOS's theme attributes. The extension carries stand-ins for the 11 MagicOS classes it uses
 * (generated by .github/scripts/honor-standins), including the two framework widgets its layouts inflate (HwToolbar,
 * ListView: Android's Toolbar and ListView); on an Honor phone the framework's own classes load first, so they never run
 * there.
 */
@Suppress("unused")
val enableNonMagicOsPatch = bytecodePatch(
    name = "Enable non-MagicOS ROM support",
    description = "Makes Honor Calculator usable on non-Honor ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_HONOR_CALCULATOR)
    dependsOn(magicResourcesPatch)
    extendWith(HONOR_CALCULATOR_EXTENSION)
}
