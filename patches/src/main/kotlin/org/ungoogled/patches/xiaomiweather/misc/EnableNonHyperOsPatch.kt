package org.ungoogled.patches.xiaomiweather.misc

import app.morphe.patcher.Fingerprint
import app.morphe.patcher.extensions.InstructionExtensions.replaceInstruction
import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import com.android.tools.smali.dexlib2.Opcode
import com.android.tools.smali.dexlib2.iface.instruction.OneRegisterInstruction
import com.android.tools.smali.dexlib2.iface.instruction.ReferenceInstruction
import com.android.tools.smali.dexlib2.iface.reference.StringReference
import org.ungoogled.patches.xiaomiweather.XiaomiWeatherConstants.COMPATIBILITY_XIAOMI_WEATHER

internal const val XIAOMI_WEATHER_EXTENSION = "extensions/xiaomiweather.mpe"

/** The settings screen's setup: finds its preferences by key and writes the night-update summary. */
private object WeatherSettingsFingerprint : Fingerprint(
    returnType = "V",
    parameters = listOf(),
    strings = listOf("key_temperature_unit", "key_night_update_auto", "HH:mm"),
)

/**
 * Settings' "Update at night automatically" summary is a format string ("between %1$s and %2$s") that Weather fills
 * in only when miuix calls the build Global (ro.product.mod_device ending in "_global", a property only Xiaomi phones
 * have); elsewhere the placeholders showed as they are. Off HyperOS Weather already runs as the Global build (see
 * miui.os.Build), so the summary is now always filled in. The property itself is left alone: Weather sends it to
 * Xiaomi's weather server.
 */
private val nightUpdateSummaryPatch = bytecodePatch(
    description = "Shows the night update hours in Weather's settings.",
) {
    execute {
        WeatherSettingsFingerprint.method.apply {
            val instructions = implementation!!.instructions.toList()
            val key = instructions.indexOfFirst {
                ((it as? ReferenceInstruction)?.reference as? StringReference)?.string == "key_night_update_auto"
            }
            if (key < 0) throw PatchException("no key_night_update_auto in Weather's settings setup")
            val check = (key + 1 until minOf(key + 12, instructions.size))
                .firstOrNull { instructions[it].opcode == Opcode.SGET_BOOLEAN }
                ?: throw PatchException("no Global check after key_night_update_auto in Weather's settings setup")
            replaceInstruction(check, "const/4 v${(instructions[check] as OneRegisterInstruction).registerA}, 0x1")
        }
    }
}

/**
 * Off HyperOS Weather dies at once on miui.os.Build (a HyperOS class). The extension carries stand-ins for the 7
 * HyperOS classes it uses (generated by .github/scripts/xiaomi-standins); on a Xiaomi phone the framework's own classes
 * load first, so they never run there.
 */
@Suppress("unused")
val enableNonHyperOsPatch = bytecodePatch(
    name = "Enable non-HyperOS ROM support",
    description = "Makes Xiaomi Weather usable on non-Xiaomi ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_XIAOMI_WEATHER)
    dependsOn(nightUpdateSummaryPatch)
    extendWith(XIAOMI_WEATHER_EXTENSION)
}
