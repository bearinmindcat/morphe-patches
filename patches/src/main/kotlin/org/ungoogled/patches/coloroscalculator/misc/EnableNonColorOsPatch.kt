package org.ungoogled.patches.coloroscalculator.misc

import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import org.ungoogled.patches.coloros.exportDynamicReceivers
import org.ungoogled.patches.coloroscalculator.ColorOsCalculatorConstants.COMPATIBILITY_COLOROS_CALCULATOR

internal const val COLOROS_CALCULATOR_EXTENSION = "extensions/coloroscalculator.mpe"

private const val RUNTIME = "Lorg/ungoogled/coloroscalculator/ColorOS;"

/**
 * Off ColorOS Calculator dies at once on com.oplus.content.OplusFeatureConfigManager (a ColorOS framework class). The
 * extension carries stand-ins for the 50 ColorOS classes it uses (generated by .github/scripts/coloros-standins); on
 * an OPPO / OnePlus / realme phone the framework's own classes load first, so they never run there. Its broadcast
 * receivers registered at run time are given the export flag Android 14+ demands of an installed app (see
 * exportDynamicReceivers).
 */
@Suppress("unused")
val enableNonColorOsPatch = bytecodePatch(
    name = "Enable non-ColorOS ROM support",
    description = "Makes OnePlus Calculator installable and usable on non-ColorOS ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_COLOROS_CALCULATOR)
    extendWith(COLOROS_CALCULATOR_EXTENSION)

    execute {
        val receivers = exportDynamicReceivers(RUNTIME)
        java.util.logging.Logger.getLogger("OnePlusCalculator").info("registerReceiver calls through ColorOS: $receivers")
        // Measured against 17.0.0: 11 calls, 3 without flags (COUI's status-bar receiver, NearX Track, the app's own).
        if (receivers < 11) throw PatchException("only $receivers registerReceiver calls found")
    }
}
