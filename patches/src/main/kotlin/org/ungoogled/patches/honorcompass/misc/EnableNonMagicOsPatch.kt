package org.ungoogled.patches.honorcompass.misc

import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import app.morphe.patcher.patch.resourcePatch
import org.ungoogled.patches.honor.followMagicDayNight
import org.ungoogled.patches.honor.replaceMagicFrameworkIds
import org.ungoogled.patches.honor.replaceMagicFrameworkReferences
import org.ungoogled.patches.honorcompass.HonorCompassConstants.COMPATIBILITY_HONOR_COMPASS

internal const val HONOR_COMPASS_EXTENSION = "extensions/honorcompass.mpe"

private val log = java.util.logging.Logger.getLogger("HonorCompass")

/**
 * What MagicOS's theme answers for the references of Compass's layouts that have no plain value on every phone
 * configuration: two colours that differ in night mode and a button style, all of which Compass also carries itself
 * (its bundled Honor UI kit has the same names and night variants), and the font families and line spacing of
 * MagicOS's text styles ("HnChinese-medium" is MagicOS's own font; Android's medium weight stands in).
 */
private val COMPASS_ANSWERS = mapOf(
    "?0x02010013" to "@style/Widget.Magic.HwButton.Emphasize", // attr/buttonStyleEmphasize (on an HwButton)
    "?0x020100c3" to "@color/magic_color_8", // attr/magicColor8 (the red "N" beside the heading)
    "?0x020100ed" to "1.1", // attr/textLineSpaceS -> dimen/magic_text_size_space_short
    "?0x020100ef" to "sans-serif", // attr/textFontFamilyRegular
    "?0x020100f0" to "sans-serif-medium", // attr/textFontFamilyMedium ("HnChinese-medium" on MagicOS)
    "@0x02050177" to "@color/magic_primary", // color/magic_primary (settings icon)
)

/**
 * MagicOS framework resources Compass's code names by id, and what it gets instead: the app's own copies (same names
 * and night variants in its bundled Honor UI kit), and Android's day/night theme for MagicOS's.
 */
private val COMPASS_CODE_ANSWERS = mapOf(
    0x020100c8 to "dimen/magic_dimens_max_start", // attr/maxPaddingStart (calibration hint margins)
    0x020100ca to "dimen/magic_dimens_max_end", // attr/maxPaddingEnd
    0x02050177 to "color/magic_primary",
    0x0205017d to "color/magic_color_5", // level: green when level
    0x02050180 to "color/magic_color_8",
    0x02060008 to "0x010302e3", // style/Theme.Magic -> android:style/Theme.DeviceDefault.DayNight
    0x020e011e to "dimen/margin_xl",
    0x020e011f to "dimen/margin_l",
    0x020e0120 to "dimen/margin_m",
    0x020e0121 to "dimen/margin_s",
    0x020e0122 to "dimen/margin_xs",
)

/**
 * Compass's layouts and styles take margins, text sizes, fonts and colours from MagicOS's theme (see
 * replaceMagicFrameworkReferences), and its one screen follows dark mode through MagicOS's theme (see followMagicDayNight).
 */
private val magicResourcesPatch = resourcePatch(
    description = "Gives Honor Compass the sizes, fonts, colours and day/night theme MagicOS would.",
) {
    execute {
        val replaced = replaceMagicFrameworkReferences(COMPASS_ANSWERS)
        log.info("MagicOS framework references: $replaced")
        // Measured against 14.0.1.174: 18 distinct references in 9 layouts, a drawable and 4 styles.
        if (replaced.size < 12) throw PatchException("only ${replaced.size} MagicOS framework references found")

        val (activities, styles) = followMagicDayNight()
        log.info("Day/night themes: $activities activities, $styles styles")
        if (activities + styles < 1) throw PatchException("themes changed: $activities activities, $styles styles")
    }
}

/**
 * Off MagicOS Compass dies at once on com.hihonor.android.os.SystemPropertiesEx (a MagicOS framework class), its layouts
 * then on MagicOS's theme attributes, and its compass view on a MagicOS framework colour it asks for by id
 * (Resources.NotFoundException). The extension carries stand-ins for the 10 MagicOS classes it uses (generated by
 * .github/scripts/honor-standins), including the framework toolbar its layouts inflate (HwToolbar: Android's Toolbar);
 * on an Honor phone the framework's own classes load first, so they never run there.
 */
@Suppress("unused")
val enableNonMagicOsPatch = bytecodePatch(
    name = "Enable non-MagicOS ROM support",
    description = "Makes Honor Compass usable on non-Honor ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_HONOR_COMPASS)
    dependsOn(magicResourcesPatch)
    extendWith(HONOR_COMPASS_EXTENSION)

    execute {
        // Measured against 14.0.1.174: 18 literals (Theme.Magic 7 times, colours, margins, two theme attributes).
        val replaced = replaceMagicFrameworkIds("Lorg/ungoogled/honorcompass/Magic;", COMPASS_CODE_ANSWERS)
        log.info("MagicOS framework ids in code: ${replaced.map { "0x%08x=%d".format(it.key, it.value) }}")
        if (replaced.size < COMPASS_CODE_ANSWERS.size) throw PatchException("only ${replaced.size} MagicOS framework ids found in code")
    }
}
