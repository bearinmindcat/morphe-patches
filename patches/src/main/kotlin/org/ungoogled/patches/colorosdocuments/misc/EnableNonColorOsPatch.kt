internal const val COLOROS_DOCUMENTS_EXTENSION = "extensions/colorosdocuments.mpe"

private const val RUNTIME = "Lorg/ungoogled/colorosdocuments/ColorOS;"
private const val DOCUMENTS = "Lorg/ungoogled/colorosdocuments/Documents;"
private const val FILE_MANAGER_SDK = "Lcom/yozo/oplus/SDK\$FileManager;"

private val log = java.util.logging.Logger.getLogger("OnePlusDocuments")

/** NearX TangramConfig's TangramConfigCtrl.Builder.build(Context): every OPPO cloud configuration starts here. */
private object CloudConfigBuildFingerprint : Fingerprint(
    returnType = "Lcom/heytap/nearx/tangramconfig/TangramConfigCtrl;",
    parameters = listOf("Landroid/content/Context;"),
    strings = listOf("ensure you have set correct product id before use configs!"),
)

/** Yozo's SDK.FileManager.isAvailable(Context, String): "use My Files' folder picker to save / export". */
private object FileManagerAvailableFingerprint : Fingerprint(
    name = "isAvailable",
    returnType = "Z",
    parameters = listOf("Landroid/content/Context;", "Ljava/lang/String;"),
    custom = { _, classDef -> classDef.type == FILE_MANAGER_SDK },
)

/** Yozo's SDK.FileManager.requireSpecifiedPathIntent(String): My Files' folder view ("Open folder"). */
private object FolderIntentFingerprint : Fingerprint(
    returnType = "Landroid/content/Intent;",
    parameters = listOf("Ljava/lang/String;"),
    strings = listOf("requireSpecifiedPathIntent_folderPath:"),
)

/** The feature check "is the Private Safe supported" (ColorOS's encryption app). */
private object PrivateSafeFeatureFingerprint : Fingerprint(
    returnType = "Z",
    parameters = listOf(),
    strings = listOf("com.oplus.filemanager.encryption_not_support"),
)

/** Reads the "Private Safe" title (string_encrypt_menu from Documents' R class). */
private fun Any.isPrivateSafeTitle(): Boolean {
    if (this !is ReferenceInstruction || opcode != Opcode.SGET) return false
    val field = reference as? FieldReference ?: return false
    return field.name == "string_encrypt_menu" && field.type == "I"
}

/**
 * Off ColorOS Documents dies at once on com.oplus.os.OplusBuild (a ColorOS framework class). The extension carries
 * stand-ins for the ColorOS classes it uses (generated by .github/scripts/coloros-standins); on an OPPO / OnePlus /
 * realme phone the framework's own classes load first, so they never run there. Its broadcast receivers registered at
 * run time are given the export flag Android 14+ demands of an installed app (see exportDynamicReceivers).
 * Beyond that: OPPO's cloud configuration never starts (it ran at every launch without asking), saving and "Open
 * folder" work without ColorOS's My Files, and the Private Safe shows only with ColorOS's encryption app.
 */
@Suppress("unused")
val enableNonColorOsPatch = bytecodePatch(
    name = "Enable non-ColorOS ROM support",
    description = "Makes OnePlus Documents installable and usable on non-ColorOS ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_COLOROS_DOCUMENTS)
    extendWith(COLOROS_DOCUMENTS_EXTENSION)

    execute {
        val receivers = exportDynamicReceivers(RUNTIME)
        log.info("registerReceiver calls through ColorOS: $receivers")
        // Measured against 17.1.26: 42 calls.
        if (receivers < 30) throw PatchException("only $receivers registerReceiver calls found")

        // OPPO's cloud configuration (product mdp_2138: remote on/off switches for the AI and conversion features, sample
        // documents) was fetched at every start with no consent (the international build counts OxygenOS's setup as
        // consent). It is never built: every caller already handles "no configuration" and keeps its built-in defaults.
        CloudConfigBuildFingerprint.method.addInstructions(
            0,
            """
                const/4 v0, 0x0
                return-object v0
            """,
        )

        // "Save" / "Save as" / "Export" open ColorOS My Files' folder picker whenever Documents' own ColorOS check passes
        // (our stand-ins make it pass), else the "My Files has been uninstalled" dialog. Without that picker Documents
        // uses its own save panel, the path it already takes on tablets.
        // The method has no spare register (.registers 2 = its two parameters), so it answers and returns at once; the
        // stock body (a ColorOS class probe, which our stand-ins always pass) stays behind as unreachable code.
        FileManagerAvailableFingerprint.method.addInstructions(
            0,
            """
                invoke-static {p0}, $DOCUMENTS->fileManagerPicker(Landroid/content/Context;)Z
                move-result p1
                return p1
            """,
        )

        // "Open folder" (after saving, converting, extracting pages) opens Android's Files app there without My Files.
        FolderIntentFingerprint.method.apply {
            val returns = implementation!!.instructions.withIndex()
                .filter { it.value.opcode == Opcode.RETURN_OBJECT }.map { it.index }
            if (returns.isEmpty()) throw PatchException("requireSpecifiedPathIntent: no return found")
            returns.reversed().forEach { index ->
                val register = getInstruction<OneRegisterInstruction>(index).registerA
                addInstructionsAtLabel(
                    index,
                    """
                        invoke-static {v$register}, $DOCUMENTS->folderIntent(Landroid/content/Intent;)Landroid/content/Intent;
                        move-result-object v$register
                    """,
                )
            }
        }

        // The Private Safe row and "move to Private Safe" only where ColorOS's encryption app is installed (the
        // stand-in's feature check says "supported", and the row did nothing).
        PrivateSafeFeatureFingerprint.method.apply {
            // v0 is a local here (the body starts by writing it), so the check may use it before the stock code runs.
            if (implementation!!.registerCount <= 1) throw PatchException("Private Safe check: no local register")
            addInstructionsWithLabels(
                0,
                """
                    invoke-static {}, $DOCUMENTS->hasPrivateSafe()Z
                    move-result v0
                    if-nez v0, :check
                    return v0
                """,
                ExternalLabel("check", getInstruction(0)),
            )
        }

        // ... and the "Private Safe" row itself (Manage tab, tablet side panel): it is added unconditionally and a tap
        // does nothing without that app. Each list's add() right after the row's title goes through Documents.
        val privateSafeRows = mutableListOf<Pair<String, Method>>()
        classDefForEach { c ->
            if (c.type.startsWith("Lorg/ungoogled/")) return@classDefForEach
            for (m in c.methods) {
                if (m.implementation?.instructions?.any { it.isPrivateSafeTitle() } == true) privateSafeRows += c.type to m
            }
        }
        var rows = 0
        for ((type, method) in privateSafeRows) {
            val mutable = mutableClassDefBy(type).methods.first {
                it.name == method.name && it.parameterTypes == method.parameterTypes && it.returnType == method.returnType
            }
            val instructions = mutable.implementation!!.instructions
            val title = instructions.indexOfFirst { it.isPrivateSafeTitle() }
            val add = (title + 1 until instructions.size).firstOrNull { i ->
                val r = (instructions[i] as? ReferenceInstruction)?.reference as? MethodReference
                instructions[i].opcode == Opcode.INVOKE_VIRTUAL && r?.definingClass == "Ljava/util/ArrayList;" &&
                    r.name == "add" && r.parameterTypes == listOf("Ljava/lang/Object;")
            } ?: throw PatchException("Private Safe row in $type.${method.name}: no list add after its title")
            val call = instructions[add] as FiveRegisterInstruction
            mutable.replaceInstruction(
                add,
                "invoke-static { v${call.registerC}, v${call.registerD} }, " +
                    "$DOCUMENTS->addPrivateSafeRow(Ljava/util/ArrayList;Ljava/lang/Object;)Z",
            )
            rows++
        }
        log.info("Private Safe rows: $rows")
        // Measured against 17.1.26: the Manage tab and the tablet side panel.
        if (rows < 2) throw PatchException("only $rows Private Safe rows found")

        // On OPPO, OnePlus and realme phones ColorOS's own apps are there but refuse it: a refusal reads as their absence.
        val (services, providers) = treatRefusedComponentsAsMissing(RUNTIME)
        log.info("Service calls: $services, provider calls: $providers through ColorOS")
    }
}
