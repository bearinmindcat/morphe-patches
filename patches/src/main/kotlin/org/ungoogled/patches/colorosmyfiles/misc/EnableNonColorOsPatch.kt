package org.ungoogled.patches.colorosmyfiles.misc

import app.morphe.patcher.Fingerprint
import app.morphe.patcher.extensions.InstructionExtensions.addInstruction
import app.morphe.patcher.extensions.InstructionExtensions.addInstructions
import app.morphe.patcher.extensions.InstructionExtensions.addInstructionsWithLabels
import app.morphe.patcher.extensions.InstructionExtensions.getInstruction
import app.morphe.patcher.util.smali.ExternalLabel
import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import com.android.tools.smali.dexlib2.AccessFlags
import com.android.tools.smali.dexlib2.iface.instruction.ReferenceInstruction
import com.android.tools.smali.dexlib2.iface.reference.FieldReference
import org.ungoogled.patches.coloros.exportDynamicReceivers
import org.ungoogled.patches.colorosmyfiles.ColorOsMyFilesConstants.COMPATIBILITY_COLOROS_MY_FILES

internal const val COLOROS_MY_FILES_EXTENSION = "extensions/colorosmyfiles.mpe"

private const val RUNTIME = "Lorg/ungoogled/colorosmyfiles/ColorOS;"
private const val MY_FILES = "Lorg/ungoogled/colorosmyfiles/MyFiles;"

private val log = java.util.logging.Logger.getLogger("OnePlusMyFiles")

/** Utils.isOnePlusBrand: "oneplus".equalsIgnoreCase(Build.BRAND). */
private object OnePlusBrandFingerprint : Fingerprint(
    accessFlags = listOf(AccessFlags.PUBLIC, AccessFlags.STATIC),
    returnType = "Z",
    parameters = listOf(),
    strings = listOf("oneplus"),
    custom = { method, _ ->
        method.implementation?.instructions?.any {
            val field = (it as? ReferenceInstruction)?.reference as? FieldReference
            field?.definingClass == "Landroid/os/Build;" && field.name == "BRAND"
        } == true
    },
)

/** The feature checks "is the Private Safe supported" (Android 11+ and Android 10 variants). */
private object PrivateSafeFeatureFingerprint : Fingerprint(
    returnType = "Z",
    parameters = listOf(),
    strings = listOf("com.oplus.filemanager.encryption_not_support"),
)

private object PrivateSafeFeatureLegacyFingerprint : Fingerprint(
    returnType = "Z",
    parameters = listOf(),
    strings = listOf("oppo.filemanager.encryption.not.support"),
)

/** CloudConfigApi's start of OPPO's NearX cloud configuration. */
private object CloudConfigInitFingerprint : Fingerprint(
    returnType = "V",
    parameters = listOf(),
    strings = listOf("CloudConfigCtrl init"),
)

/**
 * Off ColorOS My Files dies at once on com.oplus.os.OplusBuild (a ColorOS framework class). The extension carries
 * stand-ins for the ColorOS classes it uses (generated by .github/scripts/coloros-standins); on an OPPO / OnePlus /
 * realme phone the framework's own classes load first, so they never run there. Its broadcast receivers registered at
 * run time are given the export flag Android 14+ demands of an installed app (see exportDynamicReceivers).
 * Beyond that: the OnePlus build keeps its own application id on every phone (off OnePlus's phones it took OPPO's and
 * lost its recycle bin, data folder and category counts), the Private Safe shows only with ColorOS's encryption app,
 * and OPPO's cloud configuration (ad settings, storage suggestions) never starts.
 */
@Suppress("unused")
val enableNonColorOsPatch = bytecodePatch(
    name = "Enable non-ColorOS ROM support",
    description = "Makes OnePlus My Files installable and usable on non-ColorOS ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_COLOROS_MY_FILES)
    extendWith(COLOROS_MY_FILES_EXTENSION)

    execute {
        val receivers = exportDynamicReceivers(RUNTIME)
        log.info("registerReceiver calls through ColorOS: $receivers")
        // Measured against 16.12.4: 37 calls.
        if (receivers < 30) throw PatchException("only $receivers registerReceiver calls found")

        // The Private Safe row and "Lock" item only where ColorOS's encryption app is installed (see MyFiles).
        listOf(PrivateSafeFeatureFingerprint, PrivateSafeFeatureLegacyFingerprint).forEach { fingerprint ->
            fingerprint.method.apply {
                addInstructionsWithLabels(
                    0,
                    """
                        invoke-static {}, $MY_FILES->hasPrivateSafe()Z
                        move-result v0
                        if-nez v0, :check
                        return v0
                    """,
                    ExternalLabel("check", getInstruction(0)),
                )
            }
        }

        // OPPO's NearX cloud configuration (product 66452) fetches ad settings and storage-suggestion thresholds from
        // OPPO's servers; off ColorOS its region is always "CN", whose host this build leaves out (a lookup of "gn-cn"
        // that goes nowhere). It never starts: My Files uses its built-in defaults, as it does when the fetch fails.
        CloudConfigInitFingerprint.method.addInstruction(0, "return-void")

        // The app picks its application id, data folder and provider authorities by phone brand (see MyFiles).
        OnePlusBrandFingerprint.method.addInstructions(
            0,
            """
                invoke-static {}, $MY_FILES->isOnePlusBrand()Z
                move-result v0
                return v0
            """,
        )
    }
}
