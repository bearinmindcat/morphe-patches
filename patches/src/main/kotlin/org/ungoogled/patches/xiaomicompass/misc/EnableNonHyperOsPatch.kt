package org.ungoogled.patches.xiaomicompass.misc

import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import org.ungoogled.patches.xiaomi.redirectMiuiMembers
import org.ungoogled.patches.xiaomicompass.XiaomiCompassConstants.COMPATIBILITY_XIAOMI_COMPASS

internal const val XIAOMI_COMPASS_EXTENSION = "extensions/xiaomicompass.mpe"

/** Sends Compass's uses of HyperOS's additions to Android classes through Miui (see redirectMiuiMembers). */
private val miuiMembersPatch = bytecodePatch(
    description = "Answers HyperOS's additions to Android classes where the phone has none.",
) {
    extendWith(XIAOMI_COMPASS_EXTENSION)

    execute {
        val (calls, fields) = redirectMiuiMembers(
            "Lorg/ungoogled/xiaomicompass/Miui;", "Lorg/ungoogled/xiaomicompass/MiuiShims;",
        )
        java.util.logging.Logger.getLogger("XiaomiCompass").info("HyperOS members: $calls calls, $fields fields")
        // Measured against 17.1.4.1: 5 calls (miuix's ActivityOptions transitions).
        if (calls < 5) throw PatchException("only $calls HyperOS calls found")
    }
}

/**
 * Off HyperOS Compass dies at once on miui.util.HapticFeedbackUtil (a HyperOS class). The extension carries stand-ins
 * for the 5 HyperOS classes it uses (generated by .github/scripts/xiaomi-standins); on a Xiaomi phone the framework's
 * own classes load first, so they never run there.
 */
@Suppress("unused")
val enableNonHyperOsPatch = bytecodePatch(
    name = "Enable non-HyperOS ROM support",
    description = "Makes Xiaomi Compass usable on non-Xiaomi ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_XIAOMI_COMPASS)
    dependsOn(miuiMembersPatch)
    extendWith(XIAOMI_COMPASS_EXTENSION)
}
