/** The screen-lock stand-in for ColorOS's privacy-password screens (see Locks / LockActivity). */
private val lockActivityPatch = resourcePatch(
    description = "Adds the screen-lock check that guards locked notes.",
) {
    execute {
        document("AndroidManifest.xml").use { manifest ->
            val application = manifest.getElementsByTagName("application").item(0)
                ?: throw PatchException("no <application> in the manifest")
            // The screen-lock prompt (android.hardware.biometrics.BiometricPrompt) needs USE_BIOMETRIC.
            manifest.documentElement.insertBefore(
                manifest.createElement("uses-permission").apply {
                    setAttribute("android:name", "android.permission.USE_BIOMETRIC")
                },
                application,
            )
            application.appendChild(
                manifest.createElement("activity").apply {
                    setAttribute("android:name", LOCK_ACTIVITY)
                    setAttribute("android:exported", "false")
                    setAttribute("android:excludeFromRecents", "true")
                    setAttribute("android:theme", "@android:style/Theme.Translucent.NoTitleBar")
                },
            )
        }
    }
}

