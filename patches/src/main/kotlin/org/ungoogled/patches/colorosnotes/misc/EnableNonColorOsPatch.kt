/**
 * Off ColorOS Notes dies inflating its AI bar on com.oplus.os.OplusBuild$VERSION (a ColorOS framework class). The
 * extension carries stand-ins for the ColorOS classes it uses (generated by .github/scripts/coloros-standins); on an
 * OPPO / OnePlus / realme phone the framework's own classes load first, so they never run there. Its broadcast
 * receivers registered at run time are given the export flag Android 14+ demands of an installed app (see
 * exportDynamicReceivers). Beyond that: the note editor runs on the phone's own Android System WebView instead of
 * HeyTap's bundled TBL engine, OPPO's cloud configuration is never fetched, locked notes are guarded by the phone's
 * screen lock, and reminders no longer ask for "Turn screen on" where ColorOS's power manager is missing.
 */
@Suppress("unused")
val enableNonColorOsPatch = bytecodePatch(
    name = "Enable non-ColorOS ROM support",
    description = "Makes OnePlus Notes installable and usable on non-ColorOS ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_COLOROS_NOTES)
    dependsOn(lockActivityPatch)
    extendWith(COLOROS_NOTES_EXTENSION)

    execute {
        val receivers = exportDynamicReceivers(RUNTIME)
        log.info("registerReceiver calls through ColorOS: $receivers")
        // Measured against 16.6.14: 45 calls.
        if (receivers < 35) throw PatchException("only $receivers registerReceiver calls found")

        // The note editor is a WebView page. Notes ships HeyTap's own Chromium build (TBL, a 48 MB APK in its assets
        // that it installs on first use and then updates through OPPO's download services) and falls back to Android
        // System WebView where TBL can't run. Off ColorOS it always uses the system WebView, which the phone keeps up
        // to date; TBL is never installed or downloaded.
        TblInitFingerprint.method.addInstruction(0, "invoke-static {}, Lcom/heytap/tbl/webkit/TBLSdk;->forceUseSystemWebView()V")
        TblDownloadFingerprint.method.addInstruction(0, "return-void")

        // At every start (once a day) Notes fetched its AI and app settings ("ai_config_oneplus_export",
        // "app_config_oneplus_export", product mdp_1727) from OPPO's cloud configuration servers
        // (cloudconf-app-<region>.heytapmobile.com, appconf-s3-<region>.heytapdl.com) without asking. It never fetches
        // them: Notes keeps its built-in defaults, as when the fetch fails.
        CloudControlFingerprint.method.addInstruction(0, "return-void")

        // "Turn screen on" special access only where ColorOS's power manager is installed (see Notes).
        ScreenOnPermissionFingerprint.method.apply {
            addInstructionsWithLabels(
                0,
                """
                    invoke-static {}, $NOTES->hasIpeManager()Z
                    move-result v0
                    if-nez v0, :check
                    return v0
                """,
                ExternalLabel("check", getInstruction(0)),
            )
        }

        // Locked notes: the phone's screen lock instead of ColorOS's privacy password (see Locks).
        HasPrivacyPasswordFingerprint.method.apply {
            addInstructionsWithLabels(
                0,
                """
                    invoke-static {p0}, $LOCKS->hasPassword(Landroid/content/Context;)I
                    move-result v0
                    if-ltz v0, :check
                    return v0
                """,
                ExternalLabel("check", getInstruction(0)),
            )
        }
        PrivacyPasswordIntentFingerprint.method.apply {
            addInstructionsWithLabels(
                0,
                """
                    invoke-static {p0, p1}, $LOCKS->intent(Landroid/content/Context;Ljava/lang/Boolean;)Landroid/content/Intent;
                    move-result-object v0
                    if-eqz v0, :check
                    return-object v0
                """,
                ExternalLabel("check", getInstruction(0)),
            )
        }
    }
}
