internal const val XIAOMI_GALLERY_EXTENSION = "extensions/xiaomigallery.mpe"

/** Gallery requires Xiaomi's MiCloud library (micloud-sdk), which alone stops the install off HyperOS. */
private val manifestPatch = resourcePatch {
    execute {
        if (makeLibrariesOptional() == 0) throw PatchException("no required Xiaomi library in the manifest")
    }
}

/** Sends Gallery's uses of HyperOS's additions to Android classes through Miui (see redirectMiuiMembers). */
private val miuiMembersPatch = bytecodePatch(
    description = "Answers HyperOS's additions to Android classes where the phone has none.",
) {
    extendWith(XIAOMI_GALLERY_EXTENSION)

    execute {
        val (calls, fields) = redirectMiuiMembers(
            "Lorg/ungoogled/xiaomigallery/Miui;", "Lorg/ungoogled/xiaomigallery/MiuiShims;",
        )
        java.util.logging.Logger.getLogger("XiaomiGallery").info("HyperOS members: $calls calls, $fields fields")
        // Measured against 4.3.1.15-global: 5 calls (miuix's ActivityOptions transitions, getContentResolverForUser).
        if (calls < 5) throw PatchException("only $calls HyperOS calls found")
    }
}

/**
 * Off HyperOS Gallery reads Xiaomi's region properties as China's build (miuix: international only when
 * ro.product.mod_device ends in "_global"): it then waits for China's consent and never scans the phone's photos.
 */
private val globalBuildPatch = bytecodePatch(
    description = "Answers Xiaomi's region properties as the Global build does.",
) {
    extendWith(XIAOMI_GALLERY_EXTENSION)

    execute {
        val moved = redirectMiuiProperties("Lorg/ungoogled/xiaomigallery/MiuiProps;")
        java.util.logging.Logger.getLogger("XiaomiGallery").info("Property reads: $moved")
        // Measured against 4.3.1.15-global: miuix's and the app's two property wrappers plus MiCloud's callers.
        if (moved < 10) throw PatchException("only $moved property reads found")
    }
}

/**
 * Gallery needs All files access, which HyperOS gives it from the start. Its "Permissions required" page sends a
 * Global build to the app's info screen, where that switch is not: open the switch itself (see Storage).
 */
private val allFilesAccessPatch = bytecodePatch(
    description = "Opens the All files access switch from Gallery's permission page.",
) {
    extendWith(XIAOMI_GALLERY_EXTENSION)

    execute {
        StorageGuideButtonFingerprint.method.apply {
            val instructions = implementation!!.instructions
            val index = instructions.indexOfFirst {
                val r = (it as? ReferenceInstruction)?.reference as? MethodReference
                r?.definingClass == INTENT_UTIL && r.name == "enterGlobalStoragePermission"
            }
            if (index < 0) throw PatchException("Gallery's permission page no longer opens the app's info screen")
            val context = (instructions[index] as FiveRegisterInstruction).registerC
            replaceInstruction(
                index,
                "invoke-static { v$context }, Lorg/ungoogled/xiaomigallery/Storage;->permissionSettings(Landroid/content/Context;)V",
            )
        }
    }
}

/**
 * Off HyperOS Gallery cannot install (micloud-sdk) and then dies at once on miui.cloud.os.SystemProperties (a class of
 * Xiaomi's MiCloud library). The extension carries stand-ins for the Xiaomi framework and MiCloud classes it uses
 * (generated by .github/scripts/xiaomi-standins); on a Xiaomi phone the framework's own classes load first.
 */
@Suppress("unused")
val enableNonHyperOsPatch = bytecodePatch(
    name = "Enable non-HyperOS ROM support",
    description = "Makes Xiaomi Gallery installable and usable on non-Xiaomi ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_XIAOMI_GALLERY)
    dependsOn(manifestPatch, miuiMembersPatch, globalBuildPatch, allFilesAccessPatch)
    extendWith(XIAOMI_GALLERY_EXTENSION)
}
