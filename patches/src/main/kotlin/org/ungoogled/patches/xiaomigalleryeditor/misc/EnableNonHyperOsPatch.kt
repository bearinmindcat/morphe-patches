internal const val XIAOMI_GALLERY_EDITOR_EXTENSION = "extensions/xiaomigalleryeditor.mpe"

/** The editor requires Xiaomi's MiCloud library (micloud-sdk), which alone stops the install off HyperOS. */
private val manifestPatch = resourcePatch {
    execute {
        if (makeLibrariesOptional() == 0) throw PatchException("no required Xiaomi library in the manifest")
    }
}

/** Sends the editor's uses of HyperOS's additions to Android classes through Miui (see redirectMiuiMembers). */
private val miuiMembersPatch = bytecodePatch(
    description = "Answers HyperOS's additions to Android classes where the phone has none.",
) {
    extendWith(XIAOMI_GALLERY_EDITOR_EXTENSION)

    execute {
        val (calls, fields) = redirectMiuiMembers(
            "Lorg/ungoogled/xiaomigalleryeditor/Miui;", "Lorg/ungoogled/xiaomigalleryeditor/MiuiShims;",
        )
        java.util.logging.Logger.getLogger("XiaomiGalleryEditor").info("HyperOS members: $calls calls, $fields fields")
        // Measured against 2.10.40.4.8-global: 5 calls (miuix's ActivityOptions transitions).
        if (calls < 5) throw PatchException("only $calls HyperOS calls found")
    }
}

/**
 * Off HyperOS the Global editor reads Xiaomi's region properties as China's build ("global" only when
 * ro.product.mod_device ends in "_global"; ro.miui.build.region defaults to "cn"): China's cloud AI endpoints, time
 * server and region checks. Its property reads (miuix's direct calls, its own and its SDKs' reflective ones) now get
 * the Global build's answers where the phone has none, as in the Gallery port.
 */
private val globalBuildPatch = bytecodePatch(
    description = "Answers Xiaomi's region properties as the Global build does.",
) {
    extendWith(XIAOMI_GALLERY_EDITOR_EXTENSION)

    execute {
        val direct = redirectMiuiProperties("Lorg/ungoogled/xiaomigalleryeditor/MiuiProps;")
        val reflected = redirectReflectedMiuiProperties("Lorg/ungoogled/xiaomigalleryeditor/MiuiProps;")
        java.util.logging.Logger.getLogger("XiaomiGalleryEditor").info("Property reads: $direct direct, $reflected by reflection")
        // Measured against 2.10.40.4.8-global: miuix's SystemProperties wrapper, and 26 reflective lookups.
        if (direct < 4 || reflected < 20) throw PatchException("only $direct + $reflected property reads found")
    }
}

/**
 * The editor's Application installs Xiaomi's "magic string" resource hook, which needs Android's hidden
 * ResourcesManager internals (allowed to a preinstalled HyperOS app, not to an installed one): the first Activity died
 * with NoSuchMethodException. It only decrypts resources the app lists, and this build lists none: install it only
 * when there is something to decrypt (see ResGuard).
 */
private val resGuardPatch = bytecodePatch(
    description = "Skips Xiaomi's resource decryption hook when the app has nothing to decrypt.",
) {
    extendWith(XIAOMI_GALLERY_EDITOR_EXTENSION)

    execute {
        ResGuardInstallFingerprint.method.addInstructionsWithLabels(
            0,
            """
                invoke-static { p0 }, Lorg/ungoogled/xiaomigalleryeditor/ResGuard;->needed(Landroid/content/Context;)Z
                move-result v0
                if-nez v0, :install
                return-void
            """,
            ExternalLabel("install", ResGuardInstallFingerprint.method.getInstruction(0)),
        )
    }
}

/**
 * Off HyperOS the editor cannot install (micloud-sdk) and then dies opening its first photo (the resource hook). The
 * extension carries stand-ins for the 3 HyperOS classes it uses (generated by .github/scripts/xiaomi-standins); on a
 * Xiaomi phone the framework's own classes load first. Xiaomi Gallery's Edit button opens the installed editor as it is
 * (it only checks that com.miui.mediaeditor is installed).
 */
@Suppress("unused")
val enableNonHyperOsPatch = bytecodePatch(
    name = "Enable non-HyperOS ROM support",
    description = "Makes Xiaomi Gallery Editor installable and usable on non-Xiaomi ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_XIAOMI_GALLERY_EDITOR)
    dependsOn(manifestPatch, miuiMembersPatch, globalBuildPatch, resGuardPatch)
    extendWith(XIAOMI_GALLERY_EDITOR_EXTENSION)
}
