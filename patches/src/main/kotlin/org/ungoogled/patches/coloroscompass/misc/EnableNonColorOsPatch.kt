package org.ungoogled.patches.coloroscompass.misc

import app.morphe.patcher.Fingerprint
import app.morphe.patcher.extensions.InstructionExtensions.replaceInstruction
import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import com.android.tools.smali.dexlib2.Opcode
import com.android.tools.smali.dexlib2.iface.instruction.FiveRegisterInstruction
import com.android.tools.smali.dexlib2.iface.instruction.ReferenceInstruction
import com.android.tools.smali.dexlib2.iface.reference.MethodReference
import org.ungoogled.patches.coloros.exportDynamicReceivers
import org.ungoogled.patches.coloroscompass.ColorOsCompassConstants.COMPATIBILITY_COLOROS_COMPASS

internal const val COLOROS_COMPASS_EXTENSION = "extensions/coloroscompass.mpe"

private const val RUNTIME = "Lorg/ungoogled/coloroscompass/ColorOS;"
private const val PERMISSIONS = "Lorg/ungoogled/coloroscompass/Permissions;"

private val log = java.util.logging.Logger.getLogger("OnePlusCompass")

/** RuntimePermissionManager's "which manifest permissions still need asking" (Context, List), by its log text. */
private object NeedRequestPermissionsFingerprint : Fingerprint(
    returnType = "Z",
    parameters = listOf("Landroid/content/Context;", "Ljava/util/List;"),
    strings = listOf("needRequestPermissions "),
)

/**
 * Off ColorOS Compass dies at once on com.oplus.content.OplusFeatureConfigManager (a ColorOS framework class). The
 * extension carries stand-ins for the 26 ColorOS classes it uses (generated by .github/scripts/coloros-standins); on
 * an OPPO / OnePlus / realme phone the framework's own classes load first, so they never run there. Its broadcast
 * receivers registered at run time go through exportDynamicReceivers. Compass asks for every manifest permission not
 * yet granted, including two only ColorOS defines, which Android refuses without asking: it asked again on every
 * resume (an endless loop of permission screens); a permission the phone doesn't define now counts as granted there.
 */
@Suppress("unused")
val enableNonColorOsPatch = bytecodePatch(
    name = "Enable non-ColorOS ROM support",
    description = "Makes OnePlus Compass installable and usable on non-ColorOS ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_COLOROS_COMPASS)
    extendWith(COLOROS_COMPASS_EXTENSION)

    execute {
        val receivers = exportDynamicReceivers(RUNTIME)
        log.info("registerReceiver calls through ColorOS: $receivers")
        // Measured against 17.0.0: 3 calls (AppCompat's night-mode time receiver, two location helpers).
        if (receivers < 3) throw PatchException("only $receivers registerReceiver calls found")

        var checks = 0
        NeedRequestPermissionsFingerprint.method.apply {
            val instructions = implementation!!.instructions.toList()
            instructions.forEachIndexed { index, insn ->
                val ref = (insn as? ReferenceInstruction)?.reference as? MethodReference ?: return@forEachIndexed
                if (insn.opcode != Opcode.INVOKE_VIRTUAL || ref.name != "checkSelfPermission" ||
                    ref.parameterTypes != listOf("Ljava/lang/String;") || ref.returnType != "I"
                ) return@forEachIndexed
                val call = insn as FiveRegisterInstruction
                replaceInstruction(
                    index,
                    "invoke-static { v${call.registerC}, v${call.registerD} }, " +
                        "$PERMISSIONS->check(Landroid/content/Context;Ljava/lang/String;)I",
                )
                checks++
            }
        }
        log.info("Permission checks of manifest permissions: $checks")
        if (checks != 1) throw PatchException("expected 1 checkSelfPermission in the permission list, found $checks")
    }
}
