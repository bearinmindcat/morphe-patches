package org.ungoogled.patches.colorosrecorder.misc

import app.morphe.patcher.Fingerprint
import app.morphe.patcher.extensions.InstructionExtensions.addInstructions
import app.morphe.patcher.extensions.InstructionExtensions.replaceInstruction
import com.android.tools.smali.dexlib2.Opcode
import com.android.tools.smali.dexlib2.iface.instruction.FiveRegisterInstruction
import com.android.tools.smali.dexlib2.iface.instruction.ReferenceInstruction
import com.android.tools.smali.dexlib2.iface.reference.MethodReference
import com.android.tools.smali.dexlib2.iface.reference.StringReference
import app.morphe.patcher.patch.PatchException
import app.morphe.patcher.patch.bytecodePatch
import org.ungoogled.patches.coloros.exportDynamicReceivers
import org.ungoogled.patches.colorosrecorder.ColorOsRecorderConstants.COMPATIBILITY_COLOROS_RECORDER

internal const val COLOROS_RECORDER_EXTENSION = "extensions/colorosrecorder.mpe"

private const val RUNTIME = "Lorg/ungoogled/colorosrecorder/ColorOS;"

private const val FORMATS = "Lorg/ungoogled/colorosrecorder/Formats;"

private val log = java.util.logging.Logger.getLogger("OnePlusRecorder")

/** RecordConfig's toString(), by its text: the class holds a new recording's format. */
private object RecordConfigFingerprint : Fingerprint(
    returnType = "Ljava/lang/String;",
    parameters = listOf(),
    strings = listOf("RecordConfig(format="),
)

/** The settings screen's setup, which finds the "Recording file format" row and shows it. */
private object SettingsFormatRowFingerprint : Fingerprint(
    strings = listOf("pref_setting_record_format", "pref_setting_record_mode"),
)

/**
 * Off ColorOS Recorder dies at once on com.oplus.os.OplusBuild (a ColorOS framework class). The extension carries
 * stand-ins for the ColorOS classes it uses (generated by .github/scripts/coloros-standins); on an OPPO / OnePlus /
 * realme phone the framework's own classes load first, so they never run there. Its broadcast receivers registered at
 * run time go through exportDynamicReceivers. MP3, WAV and AMR need OPPO's recorder engine, a ColorOS system library:
 * without it recordings are made in AAC (Formats).
 */
@Suppress("unused")
val enableNonColorOsPatch = bytecodePatch(
    name = "Enable non-ColorOS ROM support",
    description = "Makes OnePlus Recorder installable and usable on non-ColorOS ROMs.",
    default = true,
) {
    compatibleWith(COMPATIBILITY_COLOROS_RECORDER)
    extendWith(COLOROS_RECORDER_EXTENSION)

    execute {
        val receivers = exportDynamicReceivers(RUNTIME)
        log.info("registerReceiver calls through ColorOS: $receivers")
        // Measured against 16.17.6: 45 calls.
        if (receivers < 35) throw PatchException("only $receivers registerReceiver calls found")

        // RecordConfig(format, recordType, maxDuration, maxFileSize): the format goes through Formats.
        val config = mutableClassDefBy(RecordConfigFingerprint.classDef.type)
        val init = config.methods.firstOrNull { it.name == "<init>" && it.parameterTypes.joinToString("") == "IIIJ" }
            ?: throw PatchException("RecordConfig(int, int, int, long) not found")
        init.addInstructions(0, "invoke-static {p1}, $FORMATS->recordFormat(I)I\nmove-result p1")

        // The settings row offering MP3 / AAC / WAV: its setVisible(true) goes through Formats.
        SettingsFormatRowFingerprint.method.apply {
            val instructions = implementation!!.instructions.toList()
            val key = instructions.indexOfFirst {
                ((it as? ReferenceInstruction)?.reference as? StringReference)?.string == "pref_setting_record_format"
            }
            val show = (key + 1 until minOf(key + 12, instructions.size)).firstOrNull { i ->
                val r = (instructions[i] as? ReferenceInstruction)?.reference as? MethodReference
                instructions[i].opcode == Opcode.INVOKE_VIRTUAL && r?.name == "setVisible" && r.parameterTypes == listOf("Z")
            } ?: throw PatchException("setVisible of the recording format row not found")
            val call = instructions[show] as FiveRegisterInstruction
            replaceInstruction(
                show,
                "invoke-static { v${call.registerC}, v${call.registerD} }, $FORMATS->formatRowVisible(Ljava/lang/Object;Z)V",
            )
        }
    }
}
